"""The catalogue version each list first appeared in, read from the pinned shapes (build step).

A list a configuration omits is an intentional removal (ADR 0011), but only when the list existed in the
catalogue that configuration was written against: nobody can have removed a list that came later. The engine
tells the two apart with this table, `ctld.configListSince`, embedded by the build next to `ctld.configDefault`
(ADR 0011 Addendum 3).

Only the lists that appeared after the oldest pinned shape are listed: for the others nothing earlier is known,
and an omission stays a removal, as before.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ctld_tools.catalog import Catalog
from ctld_tools.versiongap import parse_version

_VERSION_KEY = "configVersion"
_HEADER = (
    "-- GENERATED by ctld-tools (since) from tests/ci/data/catalogue_shapes. DO NOT EDIT.\n"
    "-- The catalogue version each list appeared in (ADR 0011 Addendum 3).\nctld = ctld or {}\n"
)


def list_since(catalog: Catalog, shapes: list[dict[str, Any]]) -> dict[str, str]:
    """`{list key: version}` for the lists of `catalog` that a later shape than the oldest one introduced."""
    ordered = sorted(shapes, key=lambda s: parse_version(s["version"]))
    if not ordered:
        return {}
    since: dict[str, str] = {}
    for key in catalog.keys():
        if key == _VERSION_KEY or not isinstance(catalog.get(key), (dict, list, tuple)):
            continue
        first = next((s["version"] for s in ordered if key in s["keys"]), None)
        if first is not None and first != ordered[0]["version"]:
            since[key] = first
    return since


def load_shapes(shapes_dir: str | Path) -> list[dict[str, Any]]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(Path(shapes_dir).glob("*.json"))]


def to_lua(since: dict[str, str]) -> str:
    lines = [f'    ["{key}"] = "{since[key]}",' for key in sorted(since)]
    return _HEADER + "ctld.configListSince = {\n" + "".join(line + "\n" for line in lines) + "}\n"


def write_since(catalog: Catalog, shapes_dir: str | Path, out: str | Path) -> None:
    Path(out).write_text(to_lua(list_since(catalog, load_shapes(shapes_dir))), encoding="utf-8", newline="\n")
