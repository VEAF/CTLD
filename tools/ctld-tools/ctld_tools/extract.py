def sectionize(settings: dict) -> CommentedMap:
    """Split a flat settings dict into { mm_facing, advanced }, keys sorted."""
    mm_facing = CommentedMap()
    advanced = CommentedMap()
    for key in sorted(settings.keys(), key=str):
        target = advanced if key in _ADVANCED_KEYS else mm_facing
        target[key] = settings[key]
    doc = CommentedMap()
    doc["mm_facing"] = mm_facing
    doc["advanced"] = advanced
    return doc


def extract_file(config_lua_path: str | Path, out_yaml_path: str | Path) -> None:
    """Read CTLD_config.lua defaults and write the sectioned ctld-config.yaml."""
    src_dir = Path(config_lua_path).parent
    settings = load_default_settings(src_dir)
    doc = sectionize(settings)

    yaml = YAML()
    yaml.default_flow_style = False
    yaml.width = 4096  # avoid line-wrapping long lists
    with Path(out_yaml_path).open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(
            "# GENERATED by ctld-tools (extract) — the source of truth for CTLD engine defaults.\n"
            "# Sections mm_facing / advanced are for readability; the generator merges them.\n"
        )
        yaml.dump(doc, fh)
