"""One-shot extractor: CTLD_config.lua defaults -> ctld-config.yaml.

Runs the Lua defaults (via lupa) and writes a sectioned YAML source of truth.
The mm_facing/advanced split is for readability only — the generator merges the
two sections, so the boundary never affects parity.
"""

from __future__ import annotations

from pathlib import Path

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap

from ctld_tools.luaconfig import load_default_settings

